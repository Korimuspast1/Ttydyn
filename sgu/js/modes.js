/**
 * Описание сигналов СГУ (сигнально-громкоговорящих установок) полиции России.
 *
 * Все сигналы — параметрическая реконструкция (синтез в реальном времени),
 * а не запись конкретного изделия: реальные СГУ («Элина», «Мираж», Federal Signal
 * и др.) отличаются и по тонам, и по темпу развёртки. Ползунки «Низ / Верх / Темп»
 * позволяют подогнать звук под конкретный образец.
 *
 * Разложение на слои: каждый слой — своя «сирена» (осциллятор) со своим циклом.
 * Цикл — массив сегментов { d — длительность, с, from → to — частота, Гц, level — 0..1 },
 * который может зависеть от живых параметров p = { low, high, rate }.
 */

const upDown = (p, up, down, lo, hi) => [
  { d: up / p.rate, from: lo, to: hi, level: 1 },
  { d: down / p.rate, from: hi, to: lo, level: 1 },
];

const flat = (p, d, f, level = 1) => [{ d: d / p.rate, from: f, to: f, level }];

/** Доля от диапазона (low..high) */
const at = (p, k) => p.low + (p.high - p.low) * k;

/** Фиксированная частота, масштабируемая вместе с ползунком «нижний тон» */
const hz = (p, base) => base * (p.low / 600);

