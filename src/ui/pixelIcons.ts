export function createPixelIconCanvas(name: PixelIconName, scale = 2): HTMLCanvasElement {
  const sprite = SPRITES[name] || SPRITES.trench;
  const size = 16 * scale;
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  canvas.className = 'pixel-icon';
  const ctx = canvas.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;
  for (let y = 0; y < 16; y++) {
    const row = sprite[y];
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      const color = PALETTES[ch];
      if (!color || color === 'transparent') continue;
      ctx.fillStyle = color;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }
  return canvas;
}
